/**
 * Helper to get currently active slides and calculate dynamic positions
 */
export function getActiveSlides() {
  return slideManifest.filter((slide) => slide.enabled);
}

/**
 * Returns formatted corner badge text for an active slide index
 * e.g., "02 / Who we are"
 */
export function getSlideCornerBadge(activeSlideIndex) {
  const activeList = getActiveSlides();
  const slide = activeList[activeSlideIndex];
  if (!slide || !slide.cornerLabel) return null;

  const displayNum = String(activeSlideIndex + 1).padStart(2, '0');
  const labelParts = slide.cornerLabel.split('/');
  const labelText = labelParts.length > 1 ? labelParts[1].trim() : slide.cornerLabel;
  return `${displayNum} / ${labelText}`;
}
